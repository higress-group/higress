type snapshotIngressController struct {
	common.IngressController
	configs []cfg.Config
	lists   int
}

func (d *snapshotIngressController) List() []cfg.Config {
	d.lists++
	return append([]cfg.Config(nil), d.configs...)
}

type snapshotAnnotations struct {
	annotations.AnnotationHandler
	parses int
}

func (d *snapshotAnnotations) Parse(a annotations.Annotations, c *annotations.Ingress, g *annotations.GlobalContext) error {
	d.parses++
	return d.AnnotationHandler.Parse(a, c, g)
}
func snapshotConfig(n int) (*IngressConfig, *snapshotIngressController, *snapshotAnnotations) {
	client := kube.NewFakeClient()
	options := common.Options{Enable: true, ClusterId: "snapshot", GatewayHttpPort: 80, GatewayHttpsPort: 443}
	ctrl := &snapshotIngressController{IngressController: controllerv1.NewController(client, client, options, secret.NewController(client, options))}
	for i := 0; i < n; i++ {
		ctrl.configs = append(ctrl.configs, cfg.Config{Meta: cfg.Meta{Name: fmt.Sprintf("route-%06d", i), Namespace: "default", Annotations: map[string]string{common.ClusterIdAnnotation: "snapshot"}}})
	}
	m := NewIngressConfig(client, nil, "higress-system", options)
	m.remoteIngressControllers = map[cluster.ID]common.IngressController{"snapshot": ctrl}
	ann := &snapshotAnnotations{AnnotationHandler: m.annotationHandler}
	m.annotationHandler = ann
	return m, ctrl, ann
}

func TestIndependentSnapshotsSkipIngressConversion(t *testing.T) {
	for _, kind := range []cfg.GroupVersionKind{gvk.WasmPlugin, gvk.ServiceEntry} {
		t.Run(kind.Kind, func(t *testing.T) {
			m, ctrl, ann := snapshotConfig(100)
			cachedPlugin := &extensions.WasmPlugin{Url: "file:///plugin.wasm"}
			m.wasmPlugins["cached-plugin"] = cachedPlugin
			cache := memory.NewCache()
			m.RegistryReconciler = &reconcile.Reconciler{Cache: cache}
			registryService := &cfg.Config{Meta: cfg.Meta{GroupVersionKind: gvk.ServiceEntry, Name: "registry-service", Namespace: "mcp"}, Spec: &networking.ServiceEntry{Hosts: []string{"backend.example"}}}
			cache.UpdateConfigCache(gvk.ServiceEntry, "service", registryService, false)
			cache.UpdateConfigCache(gvk.WasmPlugin, "mcp-plugin", &cfg.Config{Meta: cfg.Meta{Namespace: "higress-system"}, Spec: &registry.McpServerRule{Server: &registry.ServerConfig{Name: "test-server"}}}, false)
			for i := 0; i < 3; i++ {
				configs := m.List(kind, "")
				if kind == gvk.WasmPlugin {
					require.Len(t, configs, 2)
					plugins := map[string]cfg.Config{}
					for _, c := range configs {
						plugins[c.Name] = c
					}
					require.Equal(t, "higress-system", plugins["cached-plugin"].Namespace)
					require.True(t, proto.Equal(cachedPlugin, plugins["cached-plugin"].Spec.(proto.Message)))
					require.Contains(t, plugins, "istio-autogenerated-mcp-wasmplugin")
				} else {
					require.Len(t, configs, 1)
					require.Equal(t, registryService.Meta, configs[0].Meta)
					require.True(t, proto.Equal(registryService.Spec.(proto.Message), configs[0].Spec.(proto.Message)))
				}
			}
			require.Zero(t, ctrl.lists, "cache-backed resources must not list unrelated ingresses")
			require.Zero(t, ann.parses, "cache-backed resources must not reparse ingress annotations")
			require.Nil(t, m.listFromIngressControllers(kind, "other-namespace"))
		})
	}
}

func TestIndependentSnapshotsObserveCacheChanges(t *testing.T) {
	m, ctrl, ann := snapshotConfig(10)
	require.Empty(t, m.List(gvk.WasmPlugin, ""))
	m.wasmPlugins["new-plugin"] = &extensions.WasmPlugin{Url: "file:///new.wasm"}
	require.Len(t, m.List(gvk.WasmPlugin, ""), 1)
	delete(m.wasmPlugins, "new-plugin")
	require.Empty(t, m.List(gvk.WasmPlugin, ""))
	require.Zero(t, ctrl.lists)
	require.Zero(t, ann.parses)
}

func BenchmarkIndependentPluginSnapshot(b *testing.B) {
	for _, n := range []int{100, 1000, 5000} {
		b.Run(fmt.Sprint(n), func(b *testing.B) {
			m, _, _ := snapshotConfig(n)
			b.ReportAllocs()
			b.ResetTimer()
			for i := 0; i < b.N; i++ {
				m.List(gvk.WasmPlugin, "")
			}
		})
	}
}

func TestRouteSnapshotStillRefreshesMCPAnnotations(t *testing.T) {
	m, ctrl, ann := snapshotConfig(1)
	updater := &mockXdsUpdater{}
	m.XDSUpdater = updater
	a := ctrl.configs[0].Annotations
	a["higress.io/mcp-server"] = "true"
	a["higress.io/mcp-server-match-rule-type"] = "prefix"
	a["higress.io/mcp-server-match-rule-value"] = "/mcp"
	a["higress.io/mcp-server-upstream-type"] = "rest"
	m.List(gvk.DestinationRule, "")
	require.Len(t, m.mcpServerCache.GetMcpServers(), 1)
	require.NotNil(t, updater.lastPushRequest)
	require.Equal(t, 1, updater.lastPushRequest.Reason["mcp-server-annotation-change"])
	lists, parses := ctrl.lists, ann.parses
	updater.lastPushRequest = nil
	m.List(gvk.WasmPlugin, "")
	m.List(gvk.ServiceEntry, "")
	require.Equal(t, lists, ctrl.lists)
	require.Equal(t, parses, ann.parses)
	require.Len(t, m.mcpServerCache.GetMcpServers(), 1)
	require.Nil(t, updater.lastPushRequest)
	a["higress.io/mcp-server"] = "false"
	m.List(gvk.DestinationRule, "")
	require.Empty(t, m.mcpServerCache.GetMcpServers())
	require.NotNil(t, updater.lastPushRequest)
}

type snapshotGatewayController struct {
	common.GatewayController
	virtualServices []cfg.Config
}

func (g *snapshotGatewayController) List(kind cfg.GroupVersionKind, namespace string) []cfg.Config {
	if kind == gvk.VirtualService {
		return g.virtualServices
	}
	return nil
}
func TestPluginSnapshotPreservesGatewayAPIPlugins(t *testing.T) {
	m, ctrl, ann := snapshotConfig(10)
	m.wasmPlugins["configured-plugin"] = &extensions.WasmPlugin{Url: "file:///configured.wasm"}
	m.remoteGatewayControllers["gateway"] = &snapshotGatewayController{virtualServices: []cfg.Config{{
		Extra: map[string]any{constants.ConfigExtraPerRouteRuleInferencePoolConfigs: map[string]gatewaykube.InferencePoolRouteRuleConfig{
			"route": {Mode: gatewaykube.InferencePoolEndpointPickerModeBuiltin},
		}},
	}}}
	plugins := m.List(gvk.WasmPlugin, "")
	require.Len(t, plugins, 2)
	names := map[string]bool{}
	for _, plugin := range plugins {
		names[plugin.Name] = true
	}
	require.True(t, names["configured-plugin"])
	require.True(t, names[builtinInferenceEndpointPickerPluginName])
	require.Zero(t, ctrl.lists)
	require.Zero(t, ann.parses)
}
